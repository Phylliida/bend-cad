#!/usr/bin/env python3
"""Generate tests/chain_data.bend: a two-block plan over the dyadics.

Variables 0..3 are pinned: A = (0, 0), B = (4, 0). Block 0 finds P
(variables 4, 5) with |P - A| = |P - B| = 3, P = (2, sqrt 5) (the
circle-circle certificate of tools/gen_cc.py). Block 1 finds Q (variables
6, 7) with |Q - A| = |Q - P| = 3, Q = (1 - sqrt 15 / 2, sqrt 5 / 2 + sqrt 3);
its parameters are A and P, and P is known only within its box.
"""
import math, sys

def pos(n):
    assert n >= 1
    if n == 1: return 'S.XH{}'
    if n % 2 == 0: return 'S.XO{' + pos(n // 2) + '}'
    return 'S.XI{' + pos(n // 2) + '}'
def z(n):
    if n == 0: return 'S.Z0{}'
    if n > 0: return 'S.Zpos{' + pos(n) + '}'
    return 'S.Zneg{' + pos(-n) + '}'
def dm(m, e): return 'S.D{' + z(m) + ', ' + str(e) + 'n}'
def d(x, e): return dm(round(x * 2**e), e)
def v(i): return 'E.QVar{' + str(i) + 'n}'
def sq(a): return 'E.QMul{' + a + ', ' + a + '}'
def sub(a, b): return 'E.QSub{' + a + ', ' + b + '}'
def add(a, b): return 'E.QAdd{' + a + ', ' + b + '}'
nine = 'E.QCst{S.Q{' + z(9) + ', S.XH{}}}'
def dist2(p, q): return sub(add(sq(sub(v(p[0]), v(q[0]))), sq(sub(v(p[1]), v(q[1])))), nine)
L = lambda xs: '[' + ', '.join(xs) + ']'

A, Bp, P, Q = (0, 1), (2, 3), (4, 5), (6, 7)
eqs = [dist2(P, A), dist2(P, Bp), dist2(Q, A), dist2(Q, P)]

s5, s15, s3 = math.sqrt(5), math.sqrt(15), math.sqrt(3)
Pv = (2.0, s5)
Qv = (1 - s15 / 2, s5 / 2 + s3)

def inv2(j):
    (a, b), (c, dd) = j
    det = a * dd - b * c
    return [[dd / det, -b / det], [-c / det, a / det]]

# block 0 (unknowns P; parameters A, B): rows 2(P - A), 2(P - B)
J0 = [[2 * Pv[0], 2 * Pv[1]], [2 * (Pv[0] - 4), 2 * Pv[1]]]
Y0 = inv2(J0)
# block 1 (unknowns Q; parameters A, P): rows 2(Q - A), 2(Q - P)
J1 = [[2 * Qv[0], 2 * Qv[1]], [2 * (Qv[0] - Pv[0]), 2 * (Qv[1] - Pv[1])]]
Y1 = inv2(J1)

e_c, e_r0, e_r1, e_y = 40, 30, 26, 30
gc = [dm(0, 0), dm(0, 0), dm(4, 0), dm(0, 0), d(Pv[0], e_c), d(Pv[1], e_c), d(Qv[0], e_c), d(Qv[1], e_c)]
r0, r1 = dm(1, e_r0), dm(1, e_r1)
gr = [dm(0, 0)] * 4 + [r0, r0, r1, r1]
q = dm(1, 1)
cert0 = 'C.Cert{%s, %s, %s, %s, %s, %s}' % (L(gc[4:6]), L([r0, r0]), q, L([L([d(x, e_y) for x in row]) for row in Y0]), L(gc[0:4]), L([dm(0, 0)] * 4))
cert1 = 'C.Cert{%s, %s, %s, %s, %s, %s}' % (L(gc[6:8]), L([r1, r1]), q, L([L([d(x, e_y) for x in row]) for row in Y1]), L([gc[0], gc[1], gc[4], gc[5]]), L([dm(0, 0), dm(0, 0), r0, r0]))
# the same plan with Q's center off the solution
gc_bad = gc[:6] + [d(Qv[0] + 0.25, e_c), gc[7]]
cert1_bad = cert1.replace(gc[6], gc_bad[6], 1)

out = '''# Generated by tools/gen_chain.py: a two-block plan over the dyadics.
# Pinned A = (0, 0), B = (4, 0) (variables 0..3); block 0: P (4, 5) with
# |P - A| = |P - B| = 3; block 1: Q (6, 7) with |Q - A| = |Q - P| = 3.

import Base
import ../spec/num.bend as S
import ../spec/ring.bend as E
import ../spec/cert.bend as C
import ../spec/knum.bend as N
import ../lib/kinst.bend as KI
import ../lib/plan.bend as PL

def ch_eqs() -> List<&2, E.QExpr>:
  @EQS@

def ch_gc() -> N.KVec(~KI.dnum()):
  @GC@

def ch_gr() -> N.KVec(~KI.dnum()):
  @GR@

def ch_plan() -> PL.Plan<KI.dnum()>:
  PL.Plan{4n, [PL.PBlock{2n, [0n, 1n, 2n, 3n], @C0@}, PL.PBlock{2n, [0n, 1n, 4n, 5n], @C1@}]}

# Q's center moved by 1/4 (box and certificate alike)
def ch_gc_bad() -> N.KVec(~KI.dnum()):
  @GCB@

def ch_plan_bad() -> PL.Plan<KI.dnum()>:
  PL.Plan{4n, [PL.PBlock{2n, [0n, 1n, 2n, 3n], @C0@}, PL.PBlock{2n, [0n, 1n, 4n, 5n], @C1B@}]}
'''
for k, val in [('@EQS@', L(eqs)), ('@GC@', L(gc)), ('@GR@', L(gr)), ('@C0@', cert0), ('@C1@', cert1), ('@GCB@', L(gc_bad)), ('@C1B@', cert1_bad)]:
    out = out.replace(k, val)
sys.stdout.write(out)
