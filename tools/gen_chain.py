#!/usr/bin/env python3
"""Generate tests/chain_data.bend: a two-block plan over the dyadics.

Variables 0..3 are pinned: A = (0, 0), B = (4, 0). Block 0 finds P
(variables 4, 5) with |P - A| = |P - B| = 3, P = (2, sqrt 5) (the
circle-circle certificate of tools/gen_cc.py). Block 1 finds Q (variables
6, 7) with |Q - A| = |Q - P| = 3, Q = (1 - sqrt 15 / 2, sqrt 5 / 2 + sqrt 3);
its parameters are A and P, and P is known only within its box.
"""
import math, sys

def pos(n):
    assert n >= 1
    if n == 1: return 'S.XH{}'
    if n % 2 == 0: return 'S.XO{' + pos(n // 2) + '}'
    return 'S.XI{' + pos(n // 2) + '}'
def z(n):
    if n == 0: return 'S.Z0{}'
    if n > 0: return 'S.Zpos{' + pos(n) + '}'
    return 'S.Zneg{' + pos(-n) + '}'
def dm(m, e): return 'S.D{' + z(m) + ', ' + str(e) + 'n}'
def d(x, e): return dm(round(x * 2**e), e)
def v(i): return 'E.QVar{' + str(i) + 'n}'
def sq(a): return 'E.QMul{' + a + ', ' + a + '}'
def sub(a, b): return 'E.QSub{' + a + ', ' + b + '}'
def add(a, b): return 'E.QAdd{' + a + ', ' + b + '}'
nine = 'E.QCst{S.Q{' + z(9) + ', S.XH{}}}'
def dist2(p, q): return sub(add(sq(sub(v(p[0]), v(q[0]))), sq(sub(v(p[1]), v(q[1])))), nine)
L = lambda xs: '[' + ', '.join(xs) + ']'

A, Bp, P, Q = (0, 1), (2, 3), (4, 5), (6, 7)
eqs = [dist2(P, A), dist2(P, Bp), dist2(Q, A), dist2(Q, P)]

s5, s15, s3 = math.sqrt(5), math.sqrt(15), math.sqrt(3)
Pv = (2.0, s5)
Qv = (1 - s15 / 2, s5 / 2 + s3)

def inv2(j):
    (a, b), (c, dd) = j
    det = a * dd - b * c
    return [[dd / det, -b / det], [-c / det, a / det]]

# block 0 (unknowns P; parameters A, B): rows 2(P - A), 2(P - B)
J0 = [[2 * Pv[0], 2 * Pv[1]], [2 * (Pv[0] - 4), 2 * Pv[1]]]
Y0 = inv2(J0)
# block 1 (unknowns Q; parameters A, P): rows 2(Q - A), 2(Q - P)
J1 = [[2 * Qv[0], 2 * Qv[1]], [2 * (Qv[0] - Pv[0]), 2 * (Qv[1] - Pv[1])]]
Y1 = inv2(J1)

e_c, e_r0, e_r1, e_y = 40, 30, 26, 30
gc = [dm(0, 0), dm(0, 0), dm(4, 0), dm(0, 0), d(Pv[0], e_c), d(Pv[1], e_c), d(Qv[0], e_c), d(Qv[1], e_c)]
r0, r1 = dm(1, e_r0), dm(1, e_r1)
gr = [dm(0, 0)] * 4 + [r0, r0, r1, r1]
q = dm(1, 1)
cert0 = 'C.Cert{%s, %s, %s, %s, %s, %s}' % (L(gc[4:6]), L([r0, r0]), q, L([L([d(x, e_y) for x in row]) for row in Y0]), L(gc[0:4]), L([dm(0, 0)] * 4))
cert1 = 'C.Cert{%s, %s, %s, %s, %s, %s}' % (L(gc[6:8]), L([r1, r1]), q, L([L([d(x, e_y) for x in row]) for row in Y1]), L([gc[0], gc[1], gc[4], gc[5]]), L([dm(0, 0), dm(0, 0), r0, r0]))
# the same plan with Q's center off the solution
gc_bad = gc[:6] + [d(Qv[0] + 0.25, e_c), gc[7]]
cert1_bad = cert1.replace(gc[6], gc_bad[6], 1)

# the same system numbered otherwise: Q = (0, 1), A = (2, 3), P = (4, 5),
# B = (6, 7), equations |Q - P|, |P - A|, |Q - A|, |P - B| (each = 3)
vp = [2, 3, 6, 7, 4, 5, 0, 1]
ep = [1, 3, 2, 0]
A2, B2, P2, Q2 = (2, 3), (6, 7), (4, 5), (0, 1)
eqs2 = [dist2(Q2, P2), dist2(P2, A2), dist2(Q2, A2), dist2(P2, B2)]
gc2 = [None] * 8
gr2 = [None] * 8
for i, v_ in enumerate(vp):
    gc2[v_] = gc[i]
    gr2[v_] = gr[i]
NL = lambda xs: '[' + ', '.join(str(x) + 'n' for x in xs) + ']'

# a circle about A with radius variable r fixed at 3, P on it and at 3 from
# B; variables in block order: A (0, 1), B (2, 3), r (4), P (5, 6). Block 0
# solves r - 3 = 0 exactly (radius 0); block 1 is block 0 above with r as a
# fifth parameter (radius 0, so the same Y and radius serve).
three = dm(3, 0)
cr_gc = gc[0:4] + [three] + gc[4:6]
cr_gr = [dm(0, 0)] * 5 + [r0, r0]
cr_gr_wide = [dm(0, 0)] * 4 + [dm(4, 0), r0, r0]
cert_r = 'C.Cert{%s, %s, %s, %s, [], []}' % (L([three]), L([dm(0, 0)]), q, L([L([dm(1, 0)])]))
cert_p = 'C.Cert{%s, %s, %s, %s, %s, %s}' % (L(gc[4:6]), L([r0, r0]), q, L([L([d(x, e_y) for x in row]) for row in Y0]), L(gc[0:4] + [three]), L([dm(0, 0)] * 5))

out = '''# Generated by tools/gen_chain.py: a two-block plan over the dyadics.
# Pinned A = (0, 0), B = (4, 0) (variables 0..3); block 0: P (4, 5) with
# |P - A| = |P - B| = 3; block 1: Q (6, 7) with |Q - A| = |Q - P| = 3.

import Base
import ../spec/num.bend as S
import ../spec/ring.bend as E
import ../spec/cert.bend as C
import ../spec/knum.bend as N
import ../lib/kinst.bend as KI
import ../lib/plan.bend as PL

def ch_eqs() -> List<&2, E.QExpr>:
  @EQS@

def ch_gc() -> N.KVec(~KI.dnum()):
  @GC@

def ch_gr() -> N.KVec(~KI.dnum()):
  @GR@

def ch_plan() -> PL.Plan<KI.dnum()>:
  PL.Plan{@ID8@, @ID4@, 4n, [PL.PBlock{2n, [0n, 1n, 2n, 3n], @C0@}, PL.PBlock{2n, [0n, 1n, 4n, 5n], @C1@}]}

# Q's center moved by 1/4 (box and certificate alike)
def ch_gc_bad() -> N.KVec(~KI.dnum()):
  @GCB@

def ch_plan_bad() -> PL.Plan<KI.dnum()>:
  PL.Plan{@ID8@, @ID4@, 4n, [PL.PBlock{2n, [0n, 1n, 2n, 3n], @C0@}, PL.PBlock{2n, [0n, 1n, 4n, 5n], @C1B@}]}

# the same system, numbered otherwise, with the plan reading it in block order
def ch2_eqs() -> List<&2, E.QExpr>:
  @EQS2@

def ch2_gc() -> N.KVec(~KI.dnum()):
  @GC2@

def ch2_gr() -> N.KVec(~KI.dnum()):
  @GR2@

def ch2_plan() -> PL.Plan<KI.dnum()>:
  PL.Plan{@VP@, @EP@, 4n, [PL.PBlock{2n, [0n, 1n, 2n, 3n], @C0@}, PL.PBlock{2n, [0n, 1n, 4n, 5n], @C1@}]}

# a circle about A of radius r = 3 with P on it, |PB| = 3: variables A (0,
# 1), B (2, 3), r (4), P (5, 6); block 0 is r, block 1 is P
def cr_gc() -> N.KVec(~KI.dnum()):
  @CRGC@

def cr_gr() -> N.KVec(~KI.dnum()):
  @CRGR@

# r's radius 4: the box lets the circle's radius reach 0
def cr_gr_wide() -> N.KVec(~KI.dnum()):
  @CRGRW@

def cr_plan() -> PL.Plan<KI.dnum()>:
  PL.Plan{@ID7@, @ID3@, 4n, [PL.PBlock{1n, [], @CR0@}, PL.PBlock{2n, [0n, 1n, 2n, 3n, 4n], @CR1@}]}
'''
for k, val in [('@CRGC@', L(cr_gc)), ('@CRGRW@', L(cr_gr_wide)), ('@CRGR@', L(cr_gr)), ('@ID7@', NL(range(7))), ('@ID3@', NL(range(3))), ('@CR0@', cert_r), ('@CR1@', cert_p), ('@ID8@', NL(range(8))), ('@ID4@', NL(range(4))), ('@EQS2@', L(eqs2)), ('@GC2@', L(gc2)), ('@GR2@', L(gr2)), ('@VP@', NL(vp)), ('@EP@', NL(ep)), ('@EQS@', L(eqs)), ('@GC@', L(gc)), ('@GR@', L(gr)), ('@C0@', cert0), ('@C1@', cert1), ('@GCB@', L(gc_bad)), ('@C1B@', cert1_bad)]:
    out = out.replace(k, val)
sys.stdout.write(out)
