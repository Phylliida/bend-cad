import math, sys
def pos(n):
    assert n >= 1
    if n == 1: return 'S.XH{}'
    if n % 2 == 0: return 'S.XO{' + pos(n // 2) + '}'
    return 'S.XI{' + pos(n // 2) + '}'
def z(n):
    if n == 0: return 'S.Z0{}'
    if n > 0: return 'S.Zpos{' + pos(n) + '}'
    return 'S.Zneg{' + pos(-n) + '}'
def d(x, e):
    return 'S.D{' + z(round(x * 2**e)) + ', ' + str(e) + 'n}'
def v(i): return 'E.QVar{' + str(i) + 'n}'
def sq(a): return 'E.QMul{' + a + ', ' + a + '}'
def sub(a, b): return 'E.QSub{' + a + ', ' + b + '}'
def add(a, b): return 'E.QAdd{' + a + ', ' + b + '}'
nine = 'E.QCst{S.Q{' + z(9) + ', S.XH{}}}'
e1 = sub(add(sq(sub(v(0), v(2))), sq(sub(v(1), v(3)))), nine)
e2 = sub(add(sq(sub(v(0), v(4))), sq(sub(v(1), v(5)))), nine)
s5 = math.sqrt(5)
yc = [d(2, 0), d(s5, 40)]
yr = [d(2**-30, 30), d(2**-30, 30)]
Y = [[d(1/8, 30), d(-1/8, 30)], [d(1/(4*s5), 30), d(1/(4*s5), 30)]]
pc = [d(0, 0), d(0, 0), d(4, 0), d(0, 0)]
pr = [d(0, 0)] * 4
q = d(0.5, 1)
L = lambda xs: '[' + ', '.join(xs) + ']'
out = f'''# Generated by tools/gen_cc.py: a circle-circle block, certified over the dyadics.
# Unknowns x, y (variables 0, 1); parameters A = (0, 0), B = (4, 0) exactly
# (variables 2..5); |P - A|^2 = 9 and |P - B|^2 = 9, so P = (2, sqrt 5).

import Base
import ../spec/num.bend as S
import ../spec/ring.bend as E
import ../spec/cert.bend as C
import ../lib/kinst.bend as KI
import ../lib/cert.bend as CK

def cc_block() -> C.Block:
  C.Block{{{L([e1, e2])}, 2n}}

def cc_cert() -> C.Cert<KI.dnum()>:
  C.Cert{{{L(yc)}, {L(yr)}, {q}, {L([L(r) for r in Y])}, {L(pc)}, {L(pr)}}}
'''
sys.stdout.write(out)
