# Generates proto/int_test.bend and proto/int_test.expected: random bigint
# cases checked against Python's integers.
import random, sys
random.seed(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
def limbs(x):
    l = []
    while x:
        l.append(x % 65536); x //= 65536
    return l
def lit(x):
    ctor = "I.Neg" if x < 0 else "I.Pos"
    return ctor + "{[" + ", ".join(f"{v}n" for v in limbs(abs(x))) + "]}"
def floor_shr(a, n): return a >> n
def ceil_shr(a, n): return -((-a) >> n)
lines, exp = [], []
for i in range(60):
    a = random.choice([1, -1]) * random.getrandbits(random.randint(0, 300))
    b = random.choice([1, -1]) * random.getrandbits(random.randint(0, 300))
    if i % 7 == 0: b = a
    if i % 11 == 0: b = -a
    n = random.randint(0, 100)
    lines.append(f"    t({lit(a)}, {lit(b)}, {n}n)")
    cmpv = (a > b) - (a < b)
    exp += [str(a + b), str(a - b), str(a * b), {-1: "LT", 0: "EQ", 1: "GT"}[cmpv],
            str(floor_shr(a, n)), str(ceil_shr(a, n)), str(a << n), str(abs(a).bit_length())]
src = '''# generated by gen_int_test.py
import Base
import ./int.bend as I

def cs(c: Cmp) -> String:
  match c:
    case LT{}:
      "LT"
    case EQ{}:
      "EQ"
    case GT{}:
      "GT"

def t(+a: I.Int, +b: I.Int, +n: Nat) -> IO(Unit):
  do IO<Unit>:
    IO.print(I.Int.show(I.Int.add(a, b)))
    IO.print(I.Int.show(I.Int.sub(a, b)))
    IO.print(I.Int.show(I.Int.mul(a, b)))
    IO.print(cs(I.Int.cmp(a, b)))
    IO.print(I.Int.show(I.Int.shr_floor(a, n)))
    IO.print(I.Int.show(I.Int.shr_ceil(a, n)))
    IO.print(I.Int.show(I.Int.shl(a, n)))
    IO.print(Nat.show(I.Int.bits(a)))

def main() -> IO(Unit):
  do IO<Unit>:
''' + "\n".join(lines) + "\n"
open("proto/int_test.bend", "w").write(src)
open("proto/int_test.expected", "w").write("\n".join(exp) + "\n")
