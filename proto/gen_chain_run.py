# Generates proto/chain_run.bend: depth-N circle chains (a zigzag strip of
# triangles of height eta·L), run at several working precisions P. Also prints
# a Python prediction of the radius growth (product of per-step sensitivity
# bounds) to compare with the certificates.
import math, random, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 30
L = 50_000_000                      # 50 mm in nm
random.seed(7)

def chain(eta, jitter):
    # triangle strip B0, A0, B1, A1, …: B_m = (mL, 0), A_m = (mL + L/2, eta·L);
    # each point is at given distances from the previous two. Rotated so that
    # P1 lies on the positive x-axis (the Bend driver pins P0 = 0, P1 = (L1, 0)).
    raw = []
    for k in range(N + 2):
        m, odd = divmod(k, 2)
        x = m * L + (L / 2 if odd else 0.0)
        y = eta * L if odd else 0.0
        if k >= 2:
            x += random.uniform(-jitter, jitter); y += random.uniform(-jitter, jitter)
        raw.append((x, y))
    phi = math.atan2(raw[1][1], raw[1][0]); c, s_ = math.cos(-phi), math.sin(-phi)
    pts = [(x * c - y * s_, x * s_ + y * c) for (x, y) in raw]
    L1 = round(math.hypot(*raw[1]))
    pts[0], pts[1] = (0.0, 0.0), (float(L1), 0.0)
    steps = []
    for k in range(2, N + 2):
        a, b, p = pts[k - 2], pts[k - 1], pts[k]
        r = round(math.dist(a, p)); s = round(math.dist(b, p))
        cross = (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])
        steps.append((r, s, cross > 0))
    return L1, steps

def predict(L1, steps):
    # exact-ish solve in floats, then per step the ∞-norm sensitivity of P_k
    # to its parents: ‖J_y⁻¹ J_z‖ with J_y = 2[(y−a); (y−b)], J_z = −2[(y−a),0; 0,(y−b)]
    pts = [(0.0, 0.0), (float(L1), 0.0)]; rho = [0.0, 0.0]; logs = []
    for (r, s, left) in steps:
        a, b = pts[-2], pts[-1]
        dx, dy = b[0] - a[0], b[1] - a[1]; D = dx * dx + dy * dy
        k = (D + r * r - s * s) / (2 * D); h = math.sqrt(max(r * r - k * k * D, 0)) / math.sqrt(D)
        sg = 1 if left else -1
        y = (a[0] + k * dx - sg * h * dy, a[1] + k * dy + sg * h * dx)
        u = (y[0] - a[0], y[1] - a[1]); v = (y[0] - b[0], y[1] - b[1])
        det = u[0] * v[1] - u[1] * v[0]
        inv = [[v[1] / det, -u[1] / det], [-v[0] / det, u[0] / det]]   # (J_y/2)⁻¹
        # rows of J_z/2: row1 = −u against a, row2 = −v against b; sensitivity per unit parent move
        amp = max(abs(inv[i][0]) * (abs(u[0]) + abs(u[1])) + abs(inv[i][1]) * (abs(v[0]) + abs(v[1])) for i in range(2))
        rho.append(amp * max(rho[-1], rho[-2], 1.0) if len(rho) > 2 else amp)
        pts.append(y); logs.append(math.log2(amp))
    return logs

chains = {"well": chain(math.sqrt(3) / 2, 300_000), "flat": chain(0.08, 30_000)}
for name, (L1, st) in chains.items():
    logs = predict(L1, st)
    print(f"{name}: predicted per-step amplification log2 mean {sum(logs)/len(logs):.2f}, "
          f"total over {N} steps ≈ {sum(logs):.1f} bits (upper-bound flavour)")

def steps_lit(st):
    return "[" + ", ".join(f"C.Step{{{r}n, {s}n, {'True' if l else 'False'}{{}}}}" for r, s, l in st) + "]"

Ps = [64, 96, 128, 160, 192, 256]
body = []
for name, (L1, st) in chains.items():
    body.append(f'    IO.print("{name}: per-step log2(radius/nm) at P=256")')
    body.append(f'    IO.print(C.show.all(C.chain({name}(), {L1}n, 256n, 22n), 256n))')
    for P in Ps:
        body.append(f'    IO.print("{name} P={P}: last = " ++ C.last(C.chain({name}(), {L1}n, {P}n, {P // 16 + 6}n), {P}n))')
data = "# generated by gen_chain_run.py\nimport Base\nimport ./chain.bend as C\n\n"
for name, (L1, st) in chains.items():
    data += f"def {name}() -> List<&2, C.Step>:\n  {steps_lit(st)}\n\n"
    data += f"def {name}.L() -> Nat:\n  {L1}n\n\n"
open("proto/chain_data.bend", "w").write(data)
hdr = "# generated by gen_chain_run.py\nimport Base\nimport ./chain.bend as C\nimport ./chain_data.bend as D\n\n"
body = [b.replace("C.chain(well()", "C.chain(D.well()").replace("C.chain(flat()", "C.chain(D.flat()") for b in body]
open("proto/chain_run.bend", "w").write(hdr + "def main() -> IO(Unit):\n  do IO<Unit>:\n" + "\n".join(body) + "\n")
# bench: one chain at one P, chosen by name in the file
bench = hdr + """def main() -> IO(Unit):
  do IO<Unit>:
    IO.print("well P=96: " ++ C.last(C.chain(D.well(), D.well.L(), 96n, 12n), 96n))
    IO.print("flat P=192: " ++ C.last(C.chain(D.flat(), D.flat.L(), 192n, 18n), 192n))
"""
open("proto/chain_bench.bend", "w").write(bench)
